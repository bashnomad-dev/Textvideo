"""Модуль саммаризации транскриптов через OpenAI (gpt-4o)."""

import logging

from openai import AsyncOpenAI

from config import OPENAI_API_KEY, SUMMARY_MODEL, SUMMARY_MIN_CHARS

log = logging.getLogger(__name__)

SUMMARY_PROMPT = """Ты делаешь конспект для занятого человека, который хочет извлечь максимум за 3 минуты чтения. Это **не пересказ**, а **извлечение ценности**.

Источник: "{title}"

ЖЁСТКИЕ ПРАВИЛА:

1. **Конкретика вместо общих слов.**
   Плохо: "AI меняет разработку"
   Хорошо: "Boris говорит, что 100% его кода пишет модель; сделал 150 PR за день — личный рекорд"
   Если автор сказал цифру, имя, дату, фреймворк, инструмент — сохрани их точно.

2. **Не сглаживай острые углы.** Спорные, неочевидные, контрастные утверждения — самое ценное. Выделяй их отдельно, даже если они звучат провокационно.

3. **Цитируй точно.** Если цитата короткая и сильная — приведи её слово в слово в оригинальном языке. Не перефразируй то, что заслуживает цитаты.

4. **Не выдумывай.** Если в материале нет какого-то блока — пропусти его, не пиши "не упомянуто" и не достраивай из общих знаний.

5. **Без воды и без преамбул.** Никаких "автор рассуждает о...", "в видео обсуждаются темы...". Сразу к сути.

6. **Язык.** Объяснения по-русски. Технические термины, имена, названия инструментов — на английском (Claude, не "Клод"; PMF, не "соответствие рынку").

ФОРМАТ:

Главный тезис
Одно ёмкое предложение — что человек должен унести из материала.

TL;DR
3–5 пунктов с конкретикой (цифры, имена, инструменты).

Ключевые мысли
6–12 пунктов, развёрнутые формулировки.

Спорное / неочевидное
Утверждения, которые удивили бы стандартного слушателя. Если автор спорит с консенсусом — фиксируй.

Цитаты
Только сильные дословные. 2–5 штук. Если нет таких — пропусти секцию.

Названные инструменты, фреймворки, имена
- Tool/Person — краткий контекст (1 строка)

Применимо
Только если в материале есть реальные actionable рекомендации. Иначе пропусти.

Транскрипт:
{transcript}
"""

SUMMARY_ENABLED = bool(OPENAI_API_KEY)


async def summarize(transcript: str, title: str) -> str | None:
    """Возвращает структурированное саммари транскрипта либо None.

    None — если саммаризация отключена (нет OPENAI_API_KEY), транскрипт слишком
    короткий, или запрос к модели не удался. Вызывающий код в этом случае
    отправляет только сам транскрипт.
    """
    if not SUMMARY_ENABLED:
        return None
    if len(transcript.strip()) < SUMMARY_MIN_CHARS:
        return None

    client = AsyncOpenAI(api_key=OPENAI_API_KEY)
    try:
        response = await client.chat.completions.create(
            model=SUMMARY_MODEL,
            messages=[{
                "role": "user",
                "content": SUMMARY_PROMPT.format(title=title or "без названия", transcript=transcript),
            }],
            temperature=0.3,
        )
        return response.choices[0].message.content.strip()
    except Exception as e:
        log.exception("Саммаризация не удалась: %s", e)
        return None
